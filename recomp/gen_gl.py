CT = {'i': 'int32_t', 'p': 'uintptr_t', 'f': 'float', 'v': 'void'}


def main():
    out = ['/* Generated by recomp/gen_gl.py: AAPCS64 -> host GLES2 calling-convention thunks. */',
           '#include "rt.h"', '#include <stdio.h>', 'extern int rt_gl_trace;', 'int rt_gl_dx;',
           '/* host scene framebuffer: the engine framebuffer 0 is redirected here (see rt/present.c) */',
           'unsigned rt_gl_default_fb;', '']
    names = []
    for line in SIGS.strip().split('\n'):
        parts = line.split()
        name, ret = parts[0], parts[1]
        args = parts[2] if len(parts) > 2 else ''
        idx = len(names)
        names.append(name)
        gi = fi = 0
        vals = []
        for a in args:
            if a == 'f':
                vals.append('c->v[%d].f[0]' % fi)
                fi += 1
            else:
                src = 'c->x[%d]' % gi if gi < 8 else 'M64(c->x[31] + %d)' % ((gi - 8) * 8)
                vals.append('(%s)%s' % (CT[a], src))
                gi += 1
        if name in ('glScissor', 'glViewport'):
            vals[0] = '(int32_t)c->x[0] + rt_gl_dx'  # host menu pane offset (frontend map)
        if name == 'glBindFramebuffer':
            vals[1] = '((uint32_t)c->x[1] ? (int32_t)c->x[1] : (int32_t)rt_gl_default_fb)'
        proto = '%s (__stdcall *)(%s)' % (CT[ret], ', '.join(CT[a] for a in args) or 'void')
        call = '((%s)rt_gl_fn[%d])(%s)' % (proto, idx, ', '.join(vals))
        pre = 'if (!rt_gl_fn[%d]) rt_missing(c, "%s"); if (rt_gl_trace) rt_gl_log(c, "%s"); ' % (idx, name, name)
        if name == 'glGetIntegerv':  # the redirected framebuffer reads back as 0
            body = call + '; if ((uint32_t)c->x[0] == 0x8CA6 && rt_gl_default_fb && *(int32_t *)c->x[1] == (int32_t)rt_gl_default_fb) *(int32_t *)c->x[1] = 0;'
        elif ret == 'v':
            body = call + ';'
        elif ret == 'i':
            body = 'c->x[0] = (uint32_t)%s;' % call
        else:
            body = 'c->x[0] = (uint64_t)%s;' % call
        out.append('IMP(%s) { %s%s }' % (name, pre, body))
    out.append('')
    out.append('void *rt_gl_fn[%d];' % len(names))
    out.append('const char *const rt_gl_names[] = {%s, 0};' % ', '.join('"%s"' % n for n in names))
    out.append('const RtFunc rt_gl_shims[] = {%s};' % ', '.join('imp_' + n for n in names))
    text = '\n'.join(out) + '\n'
    try:
        if open(sys.argv[1]).read() == text:
            return
    except OSError:
        pass
    open(sys.argv[1], 'w').write(text)


main()
