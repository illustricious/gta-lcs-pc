"""Measure how much of libGame.so is rewritten in Rust and write PROGRESS.md.

A function counts as rewritten when recomp/engine exports its public symbol `G_<address>`; the
recompiled original then only runs for verification. Sizes come from the ELF symbol table of the
user's libGame.so.

Usage: python recomp/tools/rust_progress.py [path/to/libGame.so]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / '.tools' / 'py'))
from elftools.elf.elffile import ELFFile  # noqa: E402

LIB = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'local/extracted/split_config.arm64_v8a/lib/arm64-v8a/libGame.so'
GAME = re.compile(r'^_ZN\d+([Cc][A-Z]\w*)')  # C*/c* engine classes = game code


# Exported from Rust but only wrapping the recompiled original (CCamera::Process, the CHud draw parts): not rewritten.
WRAPPERS = {0x328188, 0x47db64, 0x483db0, 0x482950, 0x482b48, 0x483364}


def main():
    ported = set()
    for rs in (ROOT / 'recomp' / 'engine' / 'src').rglob('*.rs'):
        ported |= {int(a, 16) for a in re.findall(r'extern "C" fn G_([0-9a-f]+)\(', rs.read_text())}
    ported -= WRAPPERS
    elf = ELFFile(open(LIB, 'rb'))
    text = elf.get_section_by_name('.text')['sh_size'] // 4
    funcs = {}
    for s in elf.get_section_by_name('.dynsym').iter_symbols():
        if s['st_info']['type'] == 'STT_FUNC' and s['st_value'] and s['st_size']:
            funcs.setdefault(s['st_value'], (s.name, s['st_size'] // 4))
    game = {a: v for a, v in funcs.items() if GAME.match(v[0])}
    done = {a: funcs[a] for a in ported if a in funcs}
    done_game = {a: v for a, v in done.items() if a in game}

    def pct(a, b):
        return 100.0 * a / b if b else 0.0

    n_ins = sum(v[1] for v in done.values())
    rows = [
        ('Game logic functions (C*/c* classes)', len(done_game), len(game),
         sum(v[1] for v in done_game.values()), sum(v[1] for v in game.values())),
        ('All named functions', len(done), len(funcs), n_ins, sum(v[1] for v in funcs.values())),
        ('Whole .text', None, None, n_ins, text),
    ]
    out = ['# Rewritten in Rust', '',
           'Generated by `python recomp/tools/rust_progress.py`. A function counts when `recomp/engine` exports '
           'its symbol, so the game runs the Rust version.', '',
           '| Scope | Functions | Instructions |', '| --- | --- | --- |']
    for name, fd, ft, idone, itot in rows:
        f = '%d / %d (%.3f%%)' % (fd, ft, pct(fd, ft)) if ft else '-'
        out.append('| %s | %s | %d / %d (%.4f%%) |' % (name, f, idone, itot, pct(idone, itot)))
    out += ['', '## Ported functions', '', '| Address | Function | Instructions |', '| --- | --- | --- |']
    for a in sorted(done):
        out.append('| 0x%x | `%s` | %d |' % (a, done[a][0], done[a][1]))
    (ROOT / 'PROGRESS.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('\n'.join(out[4:8]))


main()
