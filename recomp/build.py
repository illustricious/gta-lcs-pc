"""Build the statically recompiled game: lift -> glue -> compile -> link.

Usage: python recomp/build.py [--jobs N] [--no-lift] [--opt O2]
       [--libs DIR] [--out DIR] [--exe PATH] [--llvm DIR] [--icon-res DIR]
Output: build/lcs.exe (or --exe).  --llvm may point at Visual Studio's LLVM (MSVC target) or at an
llvm-mingw bin folder; the installer uses llvm-mingw to build the game on the player's PC from the
libraries copied off their own phone.
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RT = ROOT / 'recomp' / 'rt'
OUT = ROOT / 'build' / 'recomp'
LIBS = ROOT / 'local' / 'extracted' / 'split_config.arm64_v8a' / 'lib' / 'arm64-v8a'
LLVM = Path(r'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Tools\Llvm\x64\bin')
EXE = ROOT / 'build' / 'lcs.exe'
ICON_RES = ROOT / 'local' / 'extracted' / 'base' / 'res'


def mingw():
    return (LLVM / 'x86_64-w64-mingw32-clang.exe').exists()
SDL = ROOT / '.tools' / 'sdl3' / 'SDL3-3.4.18'
# (prefix, library, fixed load base).  Load/initialisation order is this order.
MODULES = [
    ('O', 'libopenal.so', 0x210000000),
    ('M', 'libVendor_mpg123.so', 0x218000000),
    ('G', 'libGame.so', 0x200000000),
]
CFLAGS = ['-march=haswell', '-ffp-contract=off', '-fno-strict-aliasing', '-fwrapv', '-w', '-fno-stack-protector',
          '-I', str(RT), '-I', str(SDL / 'include')]


def run(cmd, **kw):
    r = subprocess.run(cmd, **kw)
    if r.returncode:
        sys.exit('command failed: %s' % ' '.join(map(str, cmd[:6])))


def lift():
    env = dict(os.environ, PYTHONPATH=str(ROOT / '.tools' / 'py'))
    (OUT).mkdir(parents=True, exist_ok=True)
    for prefix, lib, base in MODULES:
        run([sys.executable, str(ROOT / 'recomp' / 'lift.py'), str(LIBS / lib), str(OUT / prefix), '--prefix', prefix,
             '--base', hex(base), '--entries', str(ROOT / 'recomp' / ('entries_%s.txt' % prefix))], env=env)


def glue():
    """Bind every imported function name to another module's export, a host shim, or a trap."""
    run([sys.executable, str(ROOT / 'recomp' / 'gen_gl.py'), str(OUT / 'gl_shims.c')])
    host = set()
    for src in list(RT.glob('*.c')) + [OUT / 'gl_shims.c']:
        host |= set(re.findall(r'^IMP\((\w+)\)', src.read_text(), re.M))
    exports = {}
    imports = {}
    for prefix, _, _ in MODULES:
        for line in (OUT / prefix / ('%s_exports.txt' % prefix)).read_text().split('\n'):
            if line:
                name, addr = line.split()
                exports.setdefault(name, '%s_%s' % (prefix, addr))
        for line in (OUT / prefix / ('%s_imports.txt' % prefix)).read_text().split('\n'):
            if line.startswith('func '):
                imports.setdefault(line.split()[1], prefix)
    out = ['/* Generated by recomp/build.py: import binding. */', '#include "recomp.h"',
           'void rt_missing(CPU *c, const char *name);']
    missing = []
    for name in sorted(imports):
        if name in host:
            continue
        if name in exports:
            out.append('void %s(CPU *c);\nvoid imp_%s(CPU *c) { %s(c); }' % (exports[name], name, exports[name]))
        else:
            missing.append(name)
            out.append('void imp_%s(CPU *c) { rt_missing(c, "%s"); }' % (name, name))
    mods = ['typedef struct RtModuleDesc { const char *prefix, *file, *sha256; uint64_t base, text_lo, text_hi; '
            'const RtEntry *entries; unsigned entry_count; const RtImport *imports; } RtModuleDesc;']
    mods = []
    out[1] = '#include "rt.h"'
    for prefix, lib, base in MODULES:
        mods.append('extern const RtEntry %s_entries[]; extern const unsigned %s_entry_count; extern const RtImport %s_imports[]; '
                    'extern const char %s_sha256[]; extern const uint64_t %s_base, %s_text_lo, %s_text_hi;' % ((prefix,) * 7))
    mods.append('const RtFunc rt_missing_fns[] = {%s 0};' % ''.join('imp_%s, ' % n for n in missing))
    mods.append('unsigned rt_module_descs(RtModuleDesc *d) {')
    for i, (prefix, lib, base) in enumerate(MODULES):
        mods.append('    d[%d] = (RtModuleDesc){"%s", "%s", %s_sha256, %s_base, %s_text_lo, %s_text_hi, %s_entries, %s_entry_count, %s_imports};'
                    % (i, prefix, lib, prefix, prefix, prefix, prefix, prefix, prefix, prefix))
    mods.append('    return %d;\n}' % len(MODULES))
    text = '\n'.join(out + mods) + '\n'
    p = OUT / 'glue.c'
    if not p.exists() or p.read_text() != text:
        p.write_text(text)
    (OUT / 'missing_imports.txt').write_text('\n'.join(missing) + '\n')
    print('imports: %d names, %d host shims used, %d bound to modules, %d missing (trap on call)' % (
        len(imports), len(set(imports) & host), len([n for n in imports if n in exports and n not in host]), len(missing)))


def compile_all(jobs, opt):
    objdir = OUT / 'obj'
    objdir.mkdir(parents=True, exist_ok=True)
    clang = str(LLVM / 'clang.exe')
    flags = CFLAGS + ['-' + opt]
    if mingw():  # Windows 10 APIs (BCryptHash) and SDL's own GLES2 declarations (no Khronos headers)
        flags += ['-D_WIN32_WINNT=0x0A00', '-DSDL_USE_BUILTIN_OPENGL_DEFINITIONS']
    stamp = hashlib.sha1((' '.join(flags) + (RT / 'recomp.h').read_text()).encode()).hexdigest()[:12]
    sources = []
    for prefix, _, _ in MODULES:
        d = OUT / prefix
        sources += [(s, ['-I', str(d)]) for s in sorted(d.glob('*.c'))]
    sources += [(OUT / 'glue.c', []), (OUT / 'gl_shims.c', [])]
    rt_headers = max(h.stat().st_mtime for h in RT.glob('*.h'))
    sources += [(s, ['-g']) for s in sorted(RT.glob('*.c'))]
    todo, objs = [], []
    for src, extra in sources:
        obj = objdir / ('%s.%s.obj' % (src.stem, stamp))
        objs.append(obj)
        dep = src.stat().st_mtime
        if src.parent == RT:
            dep = max(dep, rt_headers)
        if not obj.exists() or obj.stat().st_mtime < dep:
            todo.append((src, obj, extra))
    live = {o.name for o in objs}
    for old in objdir.glob('*.obj'):
        if old.name not in live:
            old.unlink()
    t0 = time.time()
    failed = []

    def one(job):
        src, obj, extra = job
        r = subprocess.run([clang, '-c', *flags, *extra, '-o', str(obj), str(src)], capture_output=True, text=True)
        if r.returncode:
            failed.append((src, r.stderr[-3000:]))
            if obj.exists():
                obj.unlink()
        return src.name

    with ThreadPoolExecutor(jobs) as ex:
        for i, name in enumerate(ex.map(one, todo), 1):
            if i % 20 == 0 or i == len(todo):
                print('  compiled %d/%d (%.0fs)' % (i, len(todo), time.time() - t0), flush=True)
    if failed:
        for src, err in failed[:5]:
            print('FAILED', src, '\n', err)
        sys.exit(1)
    return objs, bool(todo)


def link(objs, relink):
    exe = EXE
    exe.parent.mkdir(parents=True, exist_ok=True)
    rc_dir = ROOT / 'recomp' / 'res'
    newest_res = max((f.stat().st_mtime for f in rc_dir.iterdir()), default=0) if rc_dir.exists() else 0
    if not relink and exe.exists() and exe.stat().st_mtime > newest_res:
        return exe
    res = []
    icon = OUT / 'res' / 'lcs.ico'
    r = subprocess.run([sys.executable, str(ROOT / 'recomp' / 'tools' / 'make_icon.py'), str(ICON_RES), str(icon)])
    rc = OUT / 'res' / 'lcs.rc'
    if r.returncode == 0 and icon.exists():
        rc.write_text('1 ICON "lcs.ico"\n')
    if rc.exists() and mingw():
        resobj = OUT / 'lcs.res.o'
        run([str(LLVM / 'llvm-windres.exe'), '-O', 'coff', '-o', str(resobj), str(rc)], cwd=str(rc.parent))
        res = [str(resobj)]
    elif rc.exists():
        resobj = OUT / 'lcs.res'
        if not resobj.exists() or resobj.stat().st_mtime < max(f.stat().st_mtime for f in rc.parent.iterdir()):
            run([str(LLVM / 'llvm-rc.exe'), '/fo', str(resobj), str(rc)])
        res = [str(resobj)]
    rsp = OUT / 'link.rsp'
    rsp.write_text('\n'.join('"%s"' % str(o).replace('\\', '/') for o in objs))
    if mingw():
        run([str(LLVM / 'clang.exe'), '-fuse-ld=lld', '-o', str(exe), '@' + str(rsp),
             '-L', str(SDL / 'lib' / 'x64'), '-lSDL3', '-lbcrypt', '-lsynchronization', '-lws2_32', '-lwinmm', '-luser32', '-lshell32',
             '-Wl,--stack,268435456', '-mwindows', '-static'] + res)
    else:
      run([str(LLVM / 'clang.exe'), '-fuse-ld=lld', '-g', '-o', str(exe), '@' + str(rsp),
         '-L', str(SDL / 'lib' / 'x64'), '-lSDL3', '-lbcrypt', '-lsynchronization', '-lws2_32', '-lwinmm', '-luser32', '-lshell32',
         '-Wl,/STACK:268435456', '-Wl,/MAP:' + str(ROOT / 'build' / 'lcs.map'), '-Wl,/DEBUG', '-Wl,/SUBSYSTEM:WINDOWS', '-Wl,/ENTRY:mainCRTStartup'] + res)
    dll = exe.parent / 'SDL3.dll'
    if not dll.exists():
        dll.write_bytes((SDL / 'lib' / 'x64' / 'SDL3.dll').read_bytes())
    return exe


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', type=int, default=os.cpu_count())
    ap.add_argument('--no-lift', action='store_true')
    ap.add_argument('--opt', default='O2')
    ap.add_argument('--libs'); ap.add_argument('--out'); ap.add_argument('--exe'); ap.add_argument('--llvm')
    ap.add_argument('--icon-res')
    args = ap.parse_args()
    global LIBS, OUT, EXE, LLVM, ICON_RES
    if args.libs: LIBS = Path(args.libs).resolve()
    if args.out: OUT = Path(args.out).resolve()
    if args.exe: EXE = Path(args.exe).resolve()
    if args.llvm: LLVM = Path(args.llvm).resolve()
    if args.icon_res: ICON_RES = Path(args.icon_res).resolve()
    t0 = time.time()
    if not args.no_lift:
        lift()
    glue()
    objs, changed = compile_all(args.jobs, args.opt)
    exe = link(objs, changed)
    print('built %s in %.0fs' % (exe, time.time() - t0))


if __name__ == '__main__':
    main()
